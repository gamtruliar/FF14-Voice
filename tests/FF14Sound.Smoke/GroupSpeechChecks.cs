using System.IO;
using System.Net;
using System.Net.Http;
using System.Text.Json;
using FF14Sound;
using FF14Sound.Voices;
using NAudio.Wave;

internal static class GroupSpeechChecks
{
    private static void Check(bool value, string message) { if (!value) throw new Exception(message); }
    public static async Task Run(string folder)
    {
        foreach (var name in new[] { "一同", "Everyone", "Tous", "Alle", "眾人" })
            Check(CollectiveSpeaker.IsCollective(name), "Known collective label not detected");
        foreach (var name in new[] { "Allison", "Everyone's friend", "タタル", "一同の友人", "Soldier" })
            Check(!CollectiveSpeaker.IsCollective(name), "Individual name misclassified as a crowd");
        var saved = Path.Combine(folder, "group-registry.json");
        File.WriteAllText(saved, JsonSerializer.Serialize(new[] { new NpcVoiceEntry
        { Key = "live:一同", Japanese = "一同", DescriptionVersion = 3, VoiceDescription = "成年女聲。", VoiceGender = "女聲" } }));
        var registry = new NpcVoiceRegistry(saved); registry.Load(null);
        Check(registry.Find("一同")!.VoiceDescription == CollectiveSpeaker.Description && registry.Find("一同")!.VoiceGender == "多人聲",
            "Old autogenerated female group description must migrate");
        var library = new GameVoiceLibrary();
        var group = library.Resolve("一同", "ja", new Settings(), "成年女聲。", "live:一同");
        Check(group.IsGroup && group.IsFallback && group.VoiceIdentity == "group:一同" && group.Control == CollectiveSpeaker.Description,
            "Group uses its own direction and identity instead of legacy female fallback");
        var custom = new VoiceProfile { Speaker = "一同", ReferenceAudio = "custom.wav" };
        Check(ReferenceEquals(library.Resolve("一同", "ja", new Settings { Voices = [custom] }), custom) && !GroupSpeech.Applies(custom),
            "Explicit custom reference still wins");
        var toned = DialogueTone.Apply(group, "自信堅定；情緒適中；正常語速");
        Check(SpeechSelection.Choose("original", "オーッ！！", "好！", "ja", "yue").Apply(toned).IsGroup, "Original selection retains ensemble behavior");
        var handler = new Handler(); using var speech = new SpeechClient(handler);
        var cache = Path.Combine(folder, "group-cache");
        var audio = await speech.Generate("http://localhost:8808", "オーッ！！", toned, CancellationToken.None, cacheFolder: cache);
        Check(handler.Requests.Count == 3, "A crowd needs three independent takes");
        Check(handler.Requests.Select(r => r.GetProperty("seed").GetUInt32()).Distinct().Count() == 3, "Group members need distinct stable seeds");
        Check(handler.Requests.All(r => r.GetProperty("reference_audio").ValueKind == JsonValueKind.Null &&
            r.GetProperty("text").GetString() == "オーッ！！" && r.GetProperty("control").GetString()!.Contains("本句語氣")),
            "Group never clones old shrieking reference or adds words to the dialogue");
        Check(SpeechCache.LearnedReference(cache, group) is null && !Directory.Exists(Path.Combine(cache, "learned-voices")), "Do not learn a single permanent group voice");
        Check(Directory.GetFiles(cache, "*.wav").Length == 1, "Only the completed group is cached");
        using (var wav = new WaveFileReader(new MemoryStream(audio)))
        {
            Check(wav.WaveFormat.SampleRate == 48000 && wav.WaveFormat.BitsPerSample == 16, "Group output format");
            var pcm = new byte[(int)wav.Length]; wav.ReadExactly(pcm);
            var peak = Enumerable.Range(0, pcm.Length / 2).Max(i => Math.Abs((int)BitConverter.ToInt16(pcm, i * 2))) / 32768.0;
            Check(peak > .05 && peak <= .708, "Group mix must be audible and remain below -3 dBFS");
        }
        var hit = await speech.Stream("http://localhost:8808", "オーッ！！", toned, _ => Task.CompletedTask, CancellationToken.None, 1, cache);
        Check(hit.CacheHit && !hit.Streamed && handler.Requests.Count == 3, "Streaming selection reuses complete group cache");
        var streamedCache = Path.Combine(folder, "new-group-cache");
        var fresh = await speech.Stream("http://localhost:8808", "次の句", toned, _ => Task.CompletedTask, CancellationToken.None, 2, streamedCache);
        Check(!fresh.CacheHit && !fresh.Streamed && handler.Requests.Count == 6, "Fresh group playback assembles all takes before delivering audio");
        var seeds = handler.Requests.Take(3).Select(r => r.GetProperty("seed").GetUInt32());
        Check(seeds.SequenceEqual(handler.Requests.Skip(3).Select(r => r.GetProperty("seed").GetUInt32())), "Group casting remains stable between utterances");
        using var cancel = new CancellationTokenSource();
        var calls = 0;
        try
        {
            await GroupSpeech.Render(group, _ => { calls++; cancel.Cancel(); return Task.FromResult(audio); }, cancel.Token);
            throw new Exception("Group cancellation ignored");
        }
        catch (OperationCanceledException) { }
        Check(calls == 1, "Cancellation prevents later member generations");
        Console.WriteLine("PASS: collective labels, old description migration, custom override, three voices, stable seeds, no learned solo reference, bounded mix, group cache/stream and cancellation.");
    }

    public static async Task Live(string output)
    {
        using var deadline = new CancellationTokenSource(TimeSpan.FromMinutes(3));
        using var speech = new SpeechClient();
        var group = new GameVoiceLibrary().Resolve("一同", "ja", new Settings());
        group = DialogueTone.Apply(group, "自信堅定；情緒鮮明，保持清晰自然；語速稍快");
        var audio = await speech.Generate("http://localhost:8808", "オーッ！！", group, deadline.Token, background: true);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
        await File.WriteAllBytesAsync(output, audio, deadline.Token);
        using var reader = new WaveFileReader(output);
        Console.WriteLine($"LIVE GROUP: {reader.TotalTime.TotalSeconds:F2}s; {output}");
    }

    private sealed class Handler : HttpMessageHandler
    {
        public readonly List<JsonElement> Requests = [];
        protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken token)
        {
            Check(request.RequestUri!.AbsolutePath == "/api/tts", "Group must generate complete takes, not partial member streams");
            using var body = JsonDocument.Parse(await request.Content!.ReadAsStringAsync(token));
            Requests.Add(body.RootElement.Clone());
            using var stream = new MemoryStream(); using var writer = new WaveFileWriter(stream, new WaveFormat(48000, 16, 1));
            var pcm = new byte[48000 + Requests.Count % 3 * 4800];
            for (int i = 0; i < pcm.Length / 2; i++)
                System.Buffers.Binary.BinaryPrimitives.WriteInt16LittleEndian(pcm.AsSpan(i * 2, 2),
                    (short)(30000 * Math.Sin(2 * Math.PI * (170 + Requests.Count % 3 * 50) * i / 48000)));
            writer.Write(pcm); writer.Flush();
            return new(HttpStatusCode.OK) { Content = new ByteArrayContent(stream.ToArray()) };
        }
    }
}
